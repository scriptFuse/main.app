let currentLanguage = "en";
try {
    const savedLanguage = localStorage.getItem("scriptfuse-language");
    if (savedLanguage === "en" || savedLanguage === "fr") {
        currentLanguage = savedLanguage;
    }
} catch {
    // Language switching still works when browser storage is unavailable.
}
const languageToggle = document.getElementById("lang-toggle");

function applyLanguage(language) {
    currentLanguage = language;
    try {
        localStorage.setItem("scriptfuse-language", language);
    } catch {
        // Keep the selected language for this page when storage is unavailable.
    }
    document.documentElement.lang = language;

    document.querySelectorAll("[data-key]").forEach((element) => {
        const key = element.dataset.key;
        const text = translation[language][key];

        if (text) {
            element.textContent = text;
        }
    });

    if (languageToggle) {
        languageToggle.textContent = language === "en" ? "FR" : "EN";
        languageToggle.setAttribute(
            "aria-label",
            translation[language].switchLanguage
        );
    }
    document.dispatchEvent(new Event("languagechange"));
}

applyLanguage(currentLanguage);
if (languageToggle) {
    languageToggle.addEventListener("click", () => {
        applyLanguage(currentLanguage === "en" ? "fr" : "en");
    });
}
